export type DeliveryStyle =
  | 'normal'
  | 'shout'
  | 'whisper'
  | 'thought'
  | 'sarcastic'
  | 'muttered'
  | 'trembling'
  | 'cold'
  | 'excited'
  | 'narration';

export type Genre =
  | 'noir'
  | 'manga'
  | 'cyberpunk'
  | 'webtoon-romance'
  | 'superhero'
  | 'fantasy'
  | 'comedy'
  | 'horror'
  | 'sci-fi'
  | 'slice-of-life'
  | 'action'
  | 'drama';

export type TargetFormat =
  | '3-panel-strip'
  | '4-panel-strip'
  | '6-panel-scene'
  | '9-panel-page'
  | '12-panel-episode';

export interface CharacterVoiceProfile {
  id: string;
  name: string;
  physical_description: string;
  personality: string;
  speech_style: string;
  vocabulary_level: string;
  emotional_tendencies: string;
  relationships: Record<string, string>;
  avatarColor: string;
  isAutoGenerated: boolean;
}

export interface DialogueItem {
  speaker: string;
  line: string;
  delivery: DeliveryStyle;
}

export interface ComicPanel {
  panel_number: number;
  setting: string;
  characters_present: string[];
  action: string;
  emotion: string;
  dialogue: DialogueItem[];
  narration: string;
  image_prompt: string;
  isGenerating?: boolean;
}

export interface StoryProject {
  id: string;
  title: string;
  story_idea: string;
  refined_story?: string;
  genre: Genre;
  target_format: TargetFormat;
  characters: CharacterVoiceProfile[];
  panels: ComicPanel[];
  createdAt: string;
  updatedAt: string;
}

export interface LLMSettings {
  apiKey: string;
  model: string;
  temperature: number;
  maxTokens: number;
}

export type PipelineStage =
  | 'idle'
  | 'refining-story'
  | 'extracting-characters'
  | 'generating-breakdown'
  | 'generating-dialogue'
  | 'complete'
  | 'error';

export interface PipelineStatus {
  stage: PipelineStage;
  currentPanel?: number;
  totalPanels?: number;
  message: string;
}

