export function generateId(): string {
  return Date.now().toString(36) + Math.random().toString(36).slice(2, 8);
}

export function getFormatPanelCount(format: TargetFormat): number {
  return FORMAT_OPTIONS.find(f => f.value === format)?.panels ?? 6;
}

